# Integer to float
a = 10
print(float(a))

# Float to integer
b = 10.5
print(int(b))

# Integer to string
c = 100
print(str(c))

# String to integer
d = "25"
print(int(d))

# String to float
e = "12.5"
print(float(e))

# Integer to boolean
f = 1
print(bool(f))

# List to tuple
numbers = [10, 20, 30]
print(tuple(numbers))

# Tuple to list
values = (10, 20, 30)
print(list(values))

# List to set
items = [1, 2, 2, 3]
print(set(items))
